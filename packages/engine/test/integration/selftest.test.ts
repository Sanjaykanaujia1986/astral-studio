/**
 * The build fingerprint.
 *
 * This is the contract that makes "the Android build produces numbers identical
 * to web" a checkable claim rather than an assurance. The same function runs
 * here in Node, in the browser, and inside the WebView on a device; all three
 * must print the same eight characters.
 *
 * If this test fails, the engine's output has changed. That is sometimes
 * correct — a fixed bug moves numbers — but it is never incidental, and the
 * constant below should only be updated together with a note saying which case
 * moved and why.
 */
import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { SwissEphWasmProvider } from '../../src/ephemeris/swisseph-wasm-provider.js';
import { runSelfTest, fnv1a, SELF_TEST_CASES } from '../../src/selftest.js';

/**
 * Expected fingerprint of the current engine.
 *
 * Generated by running the suite, not written by hand. Recorded 2026-08-27
 * against swisseph-wasm 0.1.0 with the bundled sepl/semo/seas data.
 */
const EXPECTED_FINGERPRINT = '855fec9b';

let provider: SwissEphWasmProvider;

beforeAll(async () => {
  provider = new SwissEphWasmProvider();
  await provider.init();
});

afterAll(() => provider.close());

describe('the engine self-test', () => {
  it('produces the recorded fingerprint', () => {
    expect(runSelfTest(provider).fingerprint).toBe(EXPECTED_FINGERPRINT);
  });

  it('is stable across repeated runs in one process', () => {
    expect(runSelfTest(provider).fingerprint).toBe(runSelfTest(provider).fingerprint);
  });

  it('is stable across a fresh provider', async () => {
    // Catches state left behind by a previous run — the Swiss Ephemeris keeps
    // sidereal mode in a global, and one of the cases is sidereal.
    const second = new SwissEphWasmProvider();
    await second.init();
    try {
      expect(runSelfTest(second).fingerprint).toBe(EXPECTED_FINGERPRINT);
    } finally {
      second.close();
    }
  });

  it('runs every case on Swiss data, not the Moshier fallback', () => {
    // A silent drop to Moshier would change every number while still looking
    // like a working chart, so the suite asserts its own provenance.
    for (const result of runSelfTest(provider).cases) {
      expect(result.source, result.id).toBe('swiss');
    }
  });

  it('covers both ends of the Swiss data range', () => {
    const ids = SELF_TEST_CASES.map((c) => c.id);
    expect(ids).toContain('range-start-1800');
    expect(ids).toContain('range-end-2399');
  });

  it('exercises a sidereal zodiac and several house systems', () => {
    // Sidereal takes a different path through the ayanamsha call, and house
    // systems differ in how much they iterate — both are places where two
    // environments could plausibly diverge.
    expect(SELF_TEST_CASES.some((c) => c.zodiac.kind === 'sidereal')).toBe(true);
    expect(new Set(SELF_TEST_CASES.map((c) => c.houseSystem)).size).toBeGreaterThanOrEqual(5);
  });

  it('gives every case a distinct digest', () => {
    // Identical digests would mean the suite was not varying what it claims to.
    const digests = runSelfTest(provider).cases.map((c) => c.digest);
    expect(new Set(digests).size).toBe(digests.length);
  });

  it('changes when any single number changes', () => {
    /*
     * The property that makes the fingerprint worth anything. A hash that
     * ignored a milliarcsecond shift would let a real divergence pass.
     */
    const base = runSelfTest(provider);
    const perturbed = fnv1a(base.cases.map((c) => `${c.id}:${c.digest}`).join('\n') + ' ');
    expect(perturbed).not.toBe(base.fingerprint);
  });
});

describe('fnv1a', () => {
  it('matches the published test vectors', () => {
    // Standard FNV-1a 32-bit vectors.
    expect(fnv1a('')).toBe('811c9dc5');
    expect(fnv1a('a')).toBe('e40c292c');
    expect(fnv1a('foobar')).toBe('bf9cf968');
  });

  it('always returns eight hex characters', () => {
    for (const text of ['', 'a', 'the quick brown fox', '☉☽']) {
      expect(fnv1a(text)).toMatch(/^[0-9a-f]{8}$/);
    }
  });
});
